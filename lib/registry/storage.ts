// Encrypted file storage for centre uploads (docs/centres/PLAN.md). Files are AES-256-GCM
// encrypted (crypto.ts) and written under UPLOAD_DIR, which MUST be outside the deploy
// directory and never under public/ — the deploy swaps .next and public, and anything under
// public is served to the world. With UPLOAD_DIR unset, uploads are simply switched off.

import { mkdir, readFile, rename, unlink, writeFile } from 'node:fs/promises';
import { join, resolve } from 'node:path';
import { randomBytes } from 'node:crypto';
import { decryptBytes, encryptBytes } from './crypto';

export const MAX_UPLOAD_BYTES = 10 * 1024 * 1024;
const DEFAULT_QUOTA_MB = 2048;

export type UploadMime = 'image/jpeg' | 'image/png' | 'image/webp' | 'application/pdf';

export const MIME_EXTENSION: Record<UploadMime, string> = {
  'image/jpeg': 'jpg',
  'image/png': 'png',
  'image/webp': 'webp',
  'application/pdf': 'pdf',
};

/** The file type from its leading bytes. The client's declared type and extension are ignored. */
export function sniffMime(b: Buffer): UploadMime | null {
  if (b.length >= 3 && b[0] === 0xff && b[1] === 0xd8 && b[2] === 0xff) return 'image/jpeg';
  if (b.length >= 8 && b.subarray(0, 8).equals(Buffer.from([0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a]))) {
    return 'image/png';
  }
  if (b.length >= 12 && b.subarray(0, 4).toString('latin1') === 'RIFF' && b.subarray(8, 12).toString('latin1') === 'WEBP') {
    return 'image/webp';
  }
  if (b.length >= 5 && b.subarray(0, 5).toString('latin1') === '%PDF-') return 'application/pdf';
  return null;
}

/** A display name only: no path parts, no control characters, bounded length. */
export function safeFileName(raw: string, mime: UploadMime): string {
  const base = raw.split(/[\\/]/).pop() ?? '';
  const cleaned = base.replace(/[\u0000-\u001f\u007f"<>:|?*]/g, '').trim().slice(0, 120);
  return cleaned || `document.${MIME_EXTENSION[mime]}`;
}

export function uploadDir(): string | null {
  const dir = process.env.UPLOAD_DIR?.trim();
  return dir ? resolve(dir) : null;
}

export function uploadsConfigured(): boolean {
  return uploadDir() !== null;
}

/** Per-centre storage cap in bytes (UPLOAD_QUOTA_MB, default 2 GB). */
export function centreQuotaBytes(): number {
  const mb = Number(process.env.UPLOAD_QUOTA_MB);
  return (Number.isFinite(mb) && mb > 0 ? mb : DEFAULT_QUOTA_MB) * 1024 * 1024;
}

// Both parts are generated by us (cuid / hex), but never join a path from unchecked text.
const SAFE = /^[a-z0-9]{8,64}$/;

function pathFor(centerId: string, storageKey: string): string {
  const dir = uploadDir();
  if (!dir) throw new Error('UPLOAD_DIR is not configured');
  if (!SAFE.test(centerId) || !SAFE.test(storageKey)) throw new Error('Unsafe storage path');
  return join(dir, centerId, `${storageKey}.bin`);
}

/** Encrypt and store; returns the storage key. Written to a temp file then renamed, so a crash leaves no half file. */
export async function putFile(centerId: string, plain: Buffer): Promise<string> {
  const storageKey = randomBytes(24).toString('hex');
  const target = pathFor(centerId, storageKey);
  await mkdir(join(target, '..'), { recursive: true, mode: 0o700 });
  const tmp = `${target}.tmp`;
  await writeFile(tmp, encryptBytes(plain, storageKey), { mode: 0o600 });
  await rename(tmp, target);
  return storageKey;
}

export async function getFile(centerId: string, storageKey: string): Promise<Buffer> {
  return decryptBytes(await readFile(pathFor(centerId, storageKey)), storageKey);
}

/** Best effort: a missing file is not an error when cleaning up. */
export async function removeFile(centerId: string, storageKey: string): Promise<void> {
  await unlink(pathFor(centerId, storageKey)).catch(() => {});
}
